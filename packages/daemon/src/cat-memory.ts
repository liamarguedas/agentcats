import { type FSWatcher, watch } from 'node:fs';
import { copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import {
  type Cat,
  fallbackVariant,
  type Learning,
  type LearningDraft,
  type LearningsVersion,
} from '@agentcats/protocol';

import { renameWithRetry, writeFileAtomic } from './fs-util.js';
import { parseLearningsFile, serializeLearningsFile, withIds } from './learnings.js';

/**
 * `.agentcats/.gitignore`, written once if missing. Learnings and profiles
 * may be committed (they are readable and useful to the team); the database,
 * stats, history and runtime files stay local.
 */
const GITIGNORE = `# Written by agentcats. Learnings, profiles and the config may be committed;
# everything else in this folder is local state.
*
!.gitignore
!agentcats.config.json
!cats/
!cats/*/
!cats/*/learnings.md
!cats/*/profile.md
`;

const PERSONA_HEADING = '## Persona';
const PERSONA_HINT = `<!-- Optional. Anything written below is added to this cat's prompt. -->`;

/** Names of history files: generated by {@link CatMemory.backup}, checked before use. */
const VERSION_ID = /^[\w-]+\.md$/;

/**
 * Each worker's folder on disk, `.agentcats/cats/<name>/`:
 *
 * - `profile.md`: role, model and created date (regenerated), plus a persona
 *   section the user may write, which goes into the cat's prompt.
 * - `learnings.md`: the source of truth for learnings, one line each.
 * - `stats.json`: XP, level and task counts, a copy of what the event log says.
 * - `history/`: earlier versions of `learnings.md`, for undo.
 *
 * File access only; what to write and when is decided by `Memory`.
 */
export class CatMemory {
  readonly #watchers = new Map<string, FSWatcher>();
  readonly #timers = new Map<string, NodeJS.Timeout>();

  constructor(private readonly runtimeDir: string) {}

  dir(name: string): string {
    return join(this.runtimeDir, 'cats', name);
  }

  learningsFile(name: string): string {
    return join(this.dir(name), 'learnings.md');
  }

  async ensureGitignore(): Promise<void> {
    const file = join(this.runtimeDir, '.gitignore');
    await mkdir(this.runtimeDir, { recursive: true });
    await writeFile(file, GITIGNORE, { flag: 'wx' }).catch((error: unknown) => {
      if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
    });
  }

  /**
   * Create the cat's folder if it is missing. A missing `learnings.md` is
   * written from `learnings` (what the log last saw), an empty list for a new cat.
   */
  async ensure(cat: Cat, learnings: readonly LearningDraft[]): Promise<void> {
    await mkdir(this.dir(cat.name), { recursive: true });
    if (!(await exists(this.learningsFile(cat.name)))) {
      await this.writeLearnings(cat.name, learnings);
    }
    await this.writeProfile(cat);
  }

  /** Learnings in the file, or `null` if there is no file. */
  async readLearnings(name: string): Promise<Learning[] | null> {
    try {
      return parseLearningsFile(await readFile(this.learningsFile(name), 'utf8'));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw error;
    }
  }

  async writeLearnings(name: string, learnings: readonly LearningDraft[]): Promise<Learning[]> {
    const drafts = learnings.map(({ text, sourceTaskId }) => ({ text, sourceTaskId }));
    await writeFileAtomic(this.learningsFile(name), serializeLearningsFile(name, drafts));
    return withIds(drafts);
  }

  /** Copy the current `learnings.md` into `history/`. Returns the version id. */
  async backup(name: string): Promise<string> {
    const historyDir = join(this.dir(name), 'history');
    await mkdir(historyDir, { recursive: true });
    const stamp = new Date().toISOString().replace(/[:.]/g, '-');
    let id = `${stamp}.md`;
    for (let n = 1; await exists(join(historyDir, id)); n++) id = `${stamp}-${String(n)}.md`;
    const file = this.learningsFile(name);
    if (await exists(file)) await copyFile(file, join(historyDir, id));
    else await writeFile(join(historyDir, id), serializeLearningsFile(name, []));
    return id;
  }

  /** Saved versions, newest first. */
  async history(name: string): Promise<LearningsVersion[]> {
    const historyDir = join(this.dir(name), 'history');
    const files = await readdir(historyDir).catch(() => [] as string[]);
    const versions: LearningsVersion[] = [];
    for (const id of files.filter((f) => VERSION_ID.test(f))) {
      const file = join(historyDir, id);
      const [text, info] = await Promise.all([readFile(file, 'utf8'), stat(file)]);
      const lines = parseLearningsFile(text).map(({ text: t, sourceTaskId }) => ({
        text: t,
        sourceTaskId,
      }));
      versions.push({ id, createdAt: Math.trunc(info.mtimeMs), lines });
    }
    return versions.sort((a, b) => b.createdAt - a.createdAt || b.id.localeCompare(a.id));
  }

  /**
   * One saved version, or `null` if there is no such version.
   * Ids are checked, so a request cannot read outside `history/`.
   */
  async readVersion(name: string, id: string): Promise<LearningDraft[] | null> {
    if (!VERSION_ID.test(id)) return null;
    try {
      const text = await readFile(join(this.dir(name), 'history', id), 'utf8');
      return parseLearningsFile(text).map(({ text: t, sourceTaskId }) => ({
        text: t,
        sourceTaskId,
      }));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw error;
    }
  }

  async writeStats(cat: Cat): Promise<void> {
    const stats = {
      xp: cat.xp,
      level: cat.level,
      tasksDone: cat.stats.completed,
      accepted: cat.stats.accepted,
      rejected: cat.stats.rejected,
    };
    await writeFileAtomic(
      join(this.dir(cat.name), 'stats.json'),
      `${JSON.stringify(stats, null, 2)}\n`,
    );
  }

  /** The persona the user wrote in `profile.md`, or `''`. */
  async persona(name: string): Promise<string> {
    const text = await readFile(join(this.dir(name), 'profile.md'), 'utf8').catch(() => '');
    return personaOf(text);
  }

  /**
   * Regenerate `profile.md`, keeping the persona the user wrote, or setting
   * `persona` when given (a hire's role).
   */
  async writeProfile(cat: Cat, newPersona?: string): Promise<void> {
    const file = join(this.dir(cat.name), 'profile.md');
    const persona = newPersona ?? personaOf(await readFile(file, 'utf8').catch(() => ''));
    const content = [
      `# ${cat.name}`,
      '',
      `- Role: ${cat.role}`,
      `- Model: ${cat.model ?? 'agent default'}`,
      `- Created: ${new Date(cat.createdAt).toISOString().slice(0, 10)}`,
      `- Id: ${cat.id}`,
      `- Look: ${cat.variant ?? fallbackVariant(cat.id)} (meme cat; see docs/assets.md in agentcats)`,
      '',
      PERSONA_HEADING,
      '',
      PERSONA_HINT,
      '',
      ...(persona ? [persona, ''] : []),
    ].join('\n');
    await writeFileAtomic(file, content);
  }

  /**
   * Call `onChange` (debounced) when the cat's folder changes on disk, for
   * hand edits of `learnings.md`. Best effort: the daemon also re-reads the
   * file before it uses it.
   */
  watch(name: string, onChange: () => void): void {
    if (this.#watchers.has(name)) return;
    try {
      const watcher = watch(this.dir(name), (_event, file) => {
        if (file !== null && file !== 'learnings.md') return;
        clearTimeout(this.#timers.get(name));
        const timer = setTimeout(() => {
          this.#timers.delete(name);
          onChange();
        }, 200);
        timer.unref();
        this.#timers.set(name, timer);
      });
      watcher.on('error', () => {
        watcher.close();
        this.#watchers.delete(name);
      });
      this.#watchers.set(name, watcher);
    } catch {
      // Watching is a convenience; reads before use keep the board right.
    }
  }

  /**
   * Move a cat's folder to `.agentcats/retired/<archive>/` with a
   * `retired.json`. Stops watching it first: on Windows a watched folder
   * cannot be moved.
   */
  async archive(name: string, archive: string, info: Record<string, unknown>): Promise<void> {
    this.unwatch(name);
    const target = join(this.runtimeDir, 'retired', archive);
    await mkdir(join(this.runtimeDir, 'retired'), { recursive: true });
    await rm(target, { recursive: true, force: true });
    if (await exists(this.dir(name))) await renameWithRetry(this.dir(name), target);
    else await mkdir(target, { recursive: true });
    await writeFile(join(target, 'retired.json'), `${JSON.stringify(info, null, 2)}\n`);
  }

  /** Move an archived folder back to `.agentcats/cats/<name>/`. */
  async unarchive(archive: string, name: string): Promise<void> {
    const source = join(this.runtimeDir, 'retired', archive);
    await mkdir(join(this.runtimeDir, 'cats'), { recursive: true });
    if (await exists(this.dir(name))) {
      throw new Error(`.agentcats/cats/${name} already exists`);
    }
    if (await exists(source)) {
      await rm(join(source, 'retired.json'), { force: true });
      await renameWithRetry(source, this.dir(name));
    }
  }

  unwatch(name: string): void {
    this.#watchers.get(name)?.close();
    this.#watchers.delete(name);
    clearTimeout(this.#timers.get(name));
    this.#timers.delete(name);
  }

  close(): void {
    for (const watcher of this.#watchers.values()) watcher.close();
    for (const timer of this.#timers.values()) clearTimeout(timer);
    this.#watchers.clear();
    this.#timers.clear();
  }
}

function personaOf(profile: string): string {
  const at = profile.indexOf(PERSONA_HEADING);
  if (at < 0) return '';
  return profile
    .slice(at + PERSONA_HEADING.length)
    .replace(/<!--[\s\S]*?-->/g, '')
    .trim();
}

async function exists(path: string): Promise<boolean> {
  return stat(path).then(
    () => true,
    () => false,
  );
}
